/// @ingroup    lib_parameter
/// @{
/// @brief      Protobuf schema describing the parameters of a firmware to host tools
/// @author     Mathis Lécrivain <lecrivain.mathis@gmail.com>
///
/// @details A parameter schema message (PB_ParameterOptions.proto) declares one field per
/// parameter: host tools read its descriptor to know the type, unit and description of each
/// parameter, and address it with the FNV-1a hash of the field name. protoc-gen-cogip-param
/// generates a `ParameterSchema<Message>` specialization in `<File>_parameters.hpp` with the
/// schema identity and the parameter keys. The firmware sends the schema identity in a
/// PB_ParameterSchema message.

#pragma once

#include <cstdint>

#include "PB_ParameterCommands.hpp"

namespace cogip {

namespace parameter {

/// @brief Parameter schema of a schema message, specialized by protoc-gen-cogip-param.
/// @tparam Message Schema message generated by EmbeddedProto.
template <typename Message> struct ParameterSchema;

/// @brief Identity of a parameter schema exposed by a firmware, whatever its schema message
struct ParameterSchemaInfo
{
    uint32_t id;      ///< Schema id
    uint32_t version; ///< Schema version
};

/// @brief Get the identity of a parameter schema.
/// @tparam Message Schema message.
/// @return Schema id and version.
template <typename Message> constexpr ParameterSchemaInfo schema_info()
{
    return {ParameterSchema<Message>::ID, ParameterSchema<Message>::VERSION};
}

/// @brief Fill the identity message of a parameter schema.
/// @param schema Parameter schema identity.
/// @param[out] message Message filled with the schema id and version.
inline void fill_schema(const ParameterSchemaInfo& schema, PB_ParameterSchema& message)
{
    message.set_id(schema.id);
    message.set_version(schema.version);
}

} // namespace parameter

} // namespace cogip

/// @}
